function setLanguage(lang) {
  const selected = translations[lang] ? lang : "en";
  localStorage.setItem("loquat-language", selected);
  document.documentElement.lang = selected === "gr" ? "el" : "en";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (translations[selected][key]) {
      el.textContent = translations[selected][key];
    }
  });

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === selected);
  });
}

document.addEventListener("DOMContentLoaded", () => {
  setLanguage(localStorage.getItem("loquat-language") || "en");

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
  });

  const header = document.querySelector(".site-header");
  const onScroll = () => {
    if (header && !header.classList.contains("solid")) {
      header.classList.toggle("scrolled", window.scrollY > 30);
    }
  };
  onScroll();
  window.addEventListener("scroll", onScroll);

  const menuToggle = document.querySelector(".menu-toggle");
  const navLinks = document.querySelector(".nav-links");
  if (menuToggle && navLinks) {
    menuToggle.addEventListener("click", () => {
      navLinks.classList.toggle("open");
      document.body.classList.toggle("menu-open");
    });
    navLinks.querySelectorAll("a").forEach((link) => {
      link.addEventListener("click", () => {
        navLinks.classList.remove("open");
        document.body.classList.remove("menu-open");
      });
    });
  }

  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) entry.target.classList.add("visible");
    });
  }, { threshold: 0.12 });

  document.querySelectorAll(".reveal").forEach((el) => observer.observe(el));

  const form = document.querySelector(".contact-form form");
  if (form) {
    form.addEventListener("submit", (event) => {
      event.preventDefault();
      alert(document.documentElement.lang === "el"
        ? "Η φόρμα είναι δοκιμαστική. Δεν έχει ενεργοποιηθεί ακόμη η αποστολή μηνυμάτων."
        : "This contact form is a preview. Email delivery is not configured yet.");
    });
  }
});


// OQ V5 interactions
document.addEventListener("DOMContentLoaded", () => {
  // FAQ accordion — one item open at a time
  const faqItems = document.querySelectorAll(".faq-item");
  faqItems.forEach((item) => {
    const button = item.querySelector(".faq-question");
    const answer = item.querySelector(".faq-answer");
    if (!button || !answer) return;

    button.addEventListener("click", () => {
      const shouldOpen = !item.classList.contains("open");

      faqItems.forEach((other) => {
        other.classList.remove("open");
        const otherButton = other.querySelector(".faq-question");
        const otherAnswer = other.querySelector(".faq-answer");
        if (otherButton) otherButton.setAttribute("aria-expanded", "false");
        if (otherAnswer) otherAnswer.style.maxHeight = null;
      });

      if (shouldOpen) {
        item.classList.add("open");
        button.setAttribute("aria-expanded", "true");
        answer.style.maxHeight = answer.scrollHeight + "px";
      }
    });
  });

  // Desktop custom cursor over product cards
  const cursor = document.querySelector(".cursor-label");
  const cards = document.querySelectorAll(".product-card");
  if (cursor && window.matchMedia("(pointer: fine)").matches) {
    document.addEventListener("mousemove", (event) => {
      cursor.style.left = event.clientX + "px";
      cursor.style.top = event.clientY + "px";
    });

    cards.forEach((card) => {
      card.addEventListener("mouseenter", () => cursor.classList.add("visible"));
      card.addEventListener("mouseleave", () => cursor.classList.remove("visible"));
    });
  }

  // Gentle parallax for hero content
  const hero = document.querySelector(".hero");
  const heroContent = document.querySelector(".hero-content");
  if (hero && heroContent && !window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    window.addEventListener("scroll", () => {
      const offset = Math.min(window.scrollY * 0.12, 42);
      heroContent.style.transform = `translateY(${offset}px)`;
      heroContent.style.opacity = String(Math.max(0.4, 1 - window.scrollY / 900));
    }, { passive: true });
  }
});


// OQ V6 video fallback
document.addEventListener("DOMContentLoaded", () => {
  const hero = document.querySelector(".hero");
  const video = document.querySelector(".hero-video");
  if (!hero || !video) return;
  const fallback = () => hero.classList.add("hero-video-fallback");
  video.addEventListener("error", fallback, { once: true });
  const attempt = video.play();
  if (attempt && typeof attempt.catch === "function") attempt.catch(fallback);
});
